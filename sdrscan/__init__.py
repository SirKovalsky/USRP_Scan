"""SDR Scan — анализатор спектра для USRP B210 (UHD + PyQt5).

ВАЖНО (Windows): нативные библиотеки UHD обязаны загрузиться РАНЬШЕ библиотек
Qt (PyQt5). Если Qt загрузится первым, создание ``uhd.usrp.MultiUSRP`` приводит
к нарушению доступа (0xC0000005) — конфликт порядка загрузки DLL. Поэтому
``import uhd`` выполняется здесь, в самом начале пакета, до любых импортов
PyQt5/pyqtgraph. На Linux этот порядок не обязателен, но и не мешает.

Пакет содержит:
    config   - модель параметров приёма/отображения
    dsp      - расчёт PSD (Welch), полоса и поиск пиков
    units    - единицы частоты (ГГц/МГц/кГц/Гц)
    presets  - каталог диапазонов (BLE, Wi-Fi, LTE, ГНСС, прочие)
    annotate - распознавание каналов/диапазонов по частоте и полосе
    device   - обёртка над UHD (MultiUSRP)
    worker   - потоки сбора данных и офлайн-обработки
    recorder - запись I/Q (.iq + .json)
    offline  - чтение записанных файлов I/Q
    gnss     - мониторинг ГНСС и детекция помех
    waterfall- виджет водопада
    gui      - главное окно PyQt
"""

